/**
 * Returns holiday name if the date is a Jewish holiday or special day, otherwise null.
 * @param {number} year - full year (e.g. 2026)
 * @param {number} month - 1-12
 * @param {number} day - 1-31
 * @returns {string|null}
 */
export const getJewishHoliday = (year, month, day) => {
  const m = String(month).padStart(2, '0');
  const d = String(day).padStart(2, '0');
  const key = `${year}-${m}-${d}`;
  return JEWISH_HOLIDAYS_MAP[key] || null;
};

/**
 * Checks if a day is Erev Chag or Yom Tov (Major holiday) where regular activities might be limited
 */
export const isMajorJewishHoliday = (year, month, day) => {
  const h = getJewishHoliday(year, month, day);
  if (!h) return false;
  return (
    h.includes('ראש השנה') ||
    h.includes('יום כיפור') ||
    h.includes('סוכות א׳') ||
    h.includes('שמחת תורה') ||
    h.includes('פסח א׳') ||
    h.includes('שביעי של פסח') ||
    h.includes('שבועות')
  );
};
